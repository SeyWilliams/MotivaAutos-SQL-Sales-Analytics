-- Segment customers into loyalty tiers(Gold, Silver,Bronze based on revenue)
SELECT CONCAT(first_name, ' ', last_name) AS full_name,
		CASE
		WHEN SUM(sales_amount)  < 500000 THEN 'Bronze'
		WHEN SUM(sales_amount) BETWEEN 500000 AND 1000000 THEN 'Silver'
		WHEN SUM(sales_amount) > 1000000 THEN 'Gold'
		END AS loyalty_tier
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY full_name;

