/*Categorize customers based on their age group.
If the age is less than 30, then youth.
If age is between 30 and 45, Adult
If age is greater than 45, Senior*/
SELECT CONCAT(first_name,' ', last_name) AS full_name, age,
		CASE 
		WHEN age < 30 THEN 'Youth'
		WHEN age BETWEEN 30 AND 45 THEN 'Adult'
		WHEN age > 45 THEN 'Senior'
		END AS age_group
FROM customers;

/* Categorize the car price
If Unit PRICE is below 10,000, affordable
If Unit Price is between 10,000 and 25,000, mid-range 
If Unit Price is greater than 25,000, luxury */
SELECT car_brand, car_model, unit_price,
		CASE
		WHEN unit_price < 10000 THEN 'Affrodable'
		WHEN unit_price BETWEEN 10000 AND 25000 THEN 'Mid-range'
		WHEN unit_price > 25000 THEN 'Luxury'
		END AS car_price_category
FROM cars;

